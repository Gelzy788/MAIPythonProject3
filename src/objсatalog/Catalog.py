from .models import Obj

class Catalog:
    """Каталог объектов. Итерация — в порядке добавления."""

    def __init__(self) -> None:
        self._items: dict[str, Obj] = {}

    def add(self, item: Obj) -> None: ...
    def get(self, item_id: str) -> Obj: ...
    def remove(self, item_id: str) -> None: ...
    def find_by_category(self, category: Category) -> list[Obj]: ...
    def find_by_name(self, query: str) -> list[Obj]: ...
    def __len__(self) -> int: ...
    def __iter__(self) -> Iterator[Obj]: ...
    def __contains__(self, item_id: object) -> bool: ...

    def _replace_all(self, items: dict[str, Obj]) -> None: ...